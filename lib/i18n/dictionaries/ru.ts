/** 1 игра, 2–4 игры, 5+ игр (with the 11–14 exception). */
function gamesRu(n: number): string {
  const mod10 = n % 10;
  const mod100 = n % 100;
  if (mod10 === 1 && mod100 !== 11) return `${n} игра`;
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return `${n} игры`;
  return `${n} игр`;
}

